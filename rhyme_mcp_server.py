"""韻検索MCPサーバー.

ラップ歌詞生成のための韻検索機能を提供するMCPサーバー。
指定した単語と韻を踏める候補を検索したり、テーマに関連する単語を検索できる。
"""

from pathlib import Path
import random
from typing import List, Tuple

import pandas as pd
from mcp.server.fastmcp import FastMCP

# --------------------------------------------------
# データ読み込み
# --------------------------------------------------
if Path("data/rhymes.csv").exists():
    DATA_PATH = Path("data/rhymes.csv")
else:
    DATA_PATH = Path("data/rhymes_compressed.csv")  # 全データのcsvがない場合は圧縮版を使用

df = pd.read_csv(DATA_PATH)

# target_word ➜ [(rhyme_word, reading, n_chars), ...]
_rhyme_dict = {
    target: list(zip(g["rhyme_word"], g["reading"], g["n_chars"])) for target, g in df.groupby("target_word", sort=False)
}

# --------------------------------------------------
# MCP サーバ初期化
# --------------------------------------------------
mcp = FastMCP("rhyme_server")


@mcp.tool()
def get_rhymes(word: str, top_k: int | None = 300) -> List[Tuple[str, str]]:
    """指定した単語と韻を踏める候補を返す.

    ソート規則:
        1. 文字数が多い順
        2. 同じ文字数の単語間はランダム抽出

    Args:
        word: インプット単語。ひらがなに直さず、元々の単語で指定する
        top_k: 返す最大件数。Noneで全件

    Returns:
        (rhyme_word, reading) のタプル列。該当がなければ空リスト。
    """
    candidates = _rhyme_dict.get(word, [])
    if not candidates:
        return []

    # シャッフルしてから n_chars で降順ソート
    random.shuffle(candidates)
    candidates.sort(key=lambda x: x[2], reverse=True)  # x[2] は n_chars

    # n_chars を落として (word, reading) だけ返す
    result = [(w, r) for w, r, _ in candidates]
    return result[:top_k] if top_k is not None else result


@mcp.tool()
def get_available_words(n: int = 300) -> List[str]:
    """韻データベースから対応可能な単語をランダムに返す.

    条件:
        - 対応する rhyme_word が50個以上あるもののみ対象
        - ランダム抽出

    Args:
        n: 返す単語数の上限

    Returns:
        韻データの対象になっている target_word のリスト
    """
    valid_targets = [t for t, rhymes in _rhyme_dict.items() if len(rhymes) >= 50]
    return random.sample(valid_targets, min(n, len(valid_targets)))


@mcp.tool()
def search_words(keyword: str, n: int = 300) -> List[str]:
    """キーワードを含む韻候補単語を検索する.

    テーマに関連する単語を直接検索したい場合に使用する。
    例: search_words("夏") → ["真夏日", "夏祭り", "夏休み", ...]

    Args:
        keyword: 検索キーワード
        n: 返す最大件数

    Returns:
        キーワードを含む単語のリスト。該当がなければ空リスト。
    """
    valid_targets = [t for t, rhymes in _rhyme_dict.items() if len(rhymes) >= 10]
    matches = [t for t in valid_targets if keyword in t]
    if not matches:
        return []
    return random.sample(matches, min(n, len(matches)))


@mcp.prompt()
def create_rap(theme: str, num_verse: int = 4) -> str:
    """ラップ歌詞を生成するプロンプトテンプレート.

    Args:
        theme: ラップのテーマ
        num_verse: 生成するバース数

    Returns:
        プロンプトテンプレート文字列
    """
    prompt = f"""
    あなたはプロのラッパーです。テーマに基づき、韻を踏んだラップ歌詞を生成してください。

    ## テーマ
    {theme}

    ## 品質の高いラップのスタイルガイド
    ### リズムと音節
    - 1行あたり16〜24音節を目安に、リズムが崩れない長さを保つ
    - 句読点や助詞で区切り、ラップ特有の「間」を意識
    - 3連符・4連符を意識した言葉の詰め込みも効果的

    ### 言葉選び
    - 漢語・カタカナ・英語をミックスし、硬軟のコントラストをつける
    - 専門用語やネットスラングでリアリティと鮮度を出す
    - オノマトペや擬態語でビートに乗る語感を演出
    - yo / yeah / ey / check it などの英語フレーズで緩急をつける

    ### 構成とトーン
    - Verse: 具体的なディスやボーストを展開、情報量多め
    - Hook: キャッチーなフレーズの反復、テーマの要約
    - Outro: 余韻を残すオチ、皮肉や自虐で締めると印象的
    - セルフボースト7割、ディス3割くらいのバランスで攻撃的すぎない仕上がりに


    ## 用語
    - **小節**: ビートに乗せる1行（20〜25文字が目安）
    - **バース**: 4小節で構成される1セクション
    - **韻セット**: 1バースで使う韻単語の組み合わせ（3〜4語）

    ## 使用ツール
    - `rap-generator.search_words`: テーマに関連するキーワードで韻が踏める単語を検索
    - `rap-generator.get_available_words`: 韻を踏める単語リストをランダム取得
    - `rap-generator.get_rhymes`: 指定した単語と韻を踏める単語を検索（独自の単語で試さず、必ずsearch_words/get_available_words経由で見つけた単語を使うこと）

    ---

    # 全体の流れ

    1. **Phase 1: 韻の広範囲探索** - 最初に1回だけ実施。テーマに関連する韻セットを複数パターン収集
    2. **Phase 2: バース作成** - 1バースずつ作成。ストックから選びつつ、必要に応じて追加探索もOK

    ---

    # Phase 1: 韻の広範囲探索
    下記のステップに厳密にしたがって実施すること。

    ## Step 1: 起点単語の収集
    以下の2つの方法を**併用**して、起点単語を幅広く収集する。

    ### 方法A: テーマからのキーワード検索
    テーマ「{theme}」から連想されるキーワードに基づいて`search_words(キーワード, n=300)` を実行する。
    - 部分一致検索なので「山」のような1文字検索だと人名が多くヒットして使えない場合もあるため注意
    - 見つからないキーワードはスキップしてOK

    ### 方法B: ランダム単語からの発見
    `get_available_words(n=300)` を実行して、韻が豊富な単語リストを取得する。
    - テーマと直接関係なくても、歌詞に使えそうな単語があればピックアップ
    - 意外な単語から面白い韻セットが見つかることも多い

    ### ピックアップ基準
    - 方法Aと方法Bの結果を合わせて、テーマに合いそうな起点単語を**10個以上**ピックアップする
    - テーマに直接関連する単語を優先しつつ、韻の幅を広げるために関連が薄い単語も2〜3個含める

    **出力必須**: 起点単語リスト
    
    ## Step 2: 韻セットの収集
    ピックアップした起点単語それぞれで `get_rhymes(単語, top_k=300)` を実行する。
    そのうえで、バース作成に使えそうな韻セットがあれば、複数パターンストックする。
    - 各起点単語について、テーマに合う韻候補が3個以上あるものがあれば、それをメモする
    - バースの中で使うので、意味のある文脈で使えそうかを重視
    - 無理やり感があったり、ほぼ同義語で韻として面白くないセットは除外
    - 韻セットが足りない場合に追加検索することは一切禁止します。必ずStep 1でピックアップした単語のみを使うこと

    **出力必須**: 各起点単語とその韻候補リスト

    ## Step 3: 韻セットのカウント
    十分な品質の韻セットが10セット以上あるかを確認する。
    - 10セット未満の場合 → Phase 1のStep 1〜2を繰り返し、韻セットを追加する
    - 10セット以上の場合 → Phase 2に進む
    ---

    # Phase 2: バース作成（1バースずつ）

    **重要ルール:**
    - 全{num_verse}バースを一度に作成してはいけない
    - 必ず1バースずつ完成させてから次に進む
    - 前バースの内容を踏まえて次のバースを作る

    ---

    ## バース1の作成

    ### Step 1-1: 韻セットを選ぶ
    Phase 1で作成した韻セットから、導入に適したものを1つ選ぶ。
    - テーマの状況説明や問題提起に使えるもの
    - ストックにピッタリのものがなければ、追加で search_words / get_rhymes で探索してもOK

    **出力必須**: 選んだ韻セット、選定理由

    ### Step 1-2: バース構想を練る
    選んだ韻セットを使って、4小節のストーリー/流れを構想する。
    - どの順番で韻単語を配置するか
    - 各小節でどんな内容を歌うか
    - 全体として意味が通るか

    **出力必須**: バース構想（各小節の概要と使う韻単語）

    ### Step 1-3: バース作成（4小節）
    構想に基づいて実際に小節を作成する。
    - 各小節の**語尾**に必ず韻セットの単語を配置（厳守）
    - 韻セットが3語の場合は、1つの小節は語尾に韻を配置せず、バースの流れを良くする
    - 各小節は**12〜16音節以内**

    **出力必須**: 作成したバース（韻を踏んでいる語尾を【】で囲む）および各小節の音節数

    ### Step 1-4: 評価と調整
    作成したバースを以下の観点で評価する:
    - 韻がちゃんと踏めているか
    - 意味が通るか（無関係な単語を無理やりあてはめていないか）
    - テーマに沿っているか

    **品質判定:**
    - 上記のいずれかを満たさない場合 → バースを破棄し、別の韻セットで再挑戦
    - 品質が十分高い場合 → 文字数を1小節12〜16音節になるよう調整

    **出力必須**: 評価結果と調整後のバース

    ---

    [バース1完成確認]
    - 完成したバース1の歌詞
    - バース1で表現した感情・状況
    - 次のバースで発展させたい要素
    - 使用済み韻セット（以降使わない）

    ---

    ## バース2の作成

    ### Step 2-1: 韻セットを選ぶ（前バースを踏まえて）

    [前バースとの接続を考える]
    - バース1で表現した感情: [確認]
    - 次に発展させる方向: 感情のエスカレーション / 視点の転換 / 具体化

    ストックした韻セットから、上記の方向性に合うものを選ぶ。
    - 既存の韻セットにこだわらず、マッチするもんがなければsearch_wordsやget_rhymesを用いて追加で韻の探索を行う
    - 前バースで使った韻セットは使わない

    **出力必須**: 前バースとのつながり、選んだ韻セット、選定理由

    ### Step 2-2〜2-4: （Step 1-2〜1-4と同じ手順）

    ---

    [バース2完成確認]
    - 完成したバース2の歌詞
    - バース1→2での感情/ストーリーの変化
    - 次のバースで発展させたい要素
    - 使用済み韻セット

    ---

    ## バース3の作成

    [これまでの流れを確認]
    - バース1: [内容・感情]
    - バース2: [内容・感情]
    - バース3の方向性: クライマックスに向けた盛り上げ or 転換点

    （以下、バース2と同様の手順）

    ---

    ## バース4の作成（最終バース）

    [最終バースとしての役割]
    - これまでの流れ: バース1→2→3の感情の軌跡を確認
    - 締め方の選択:
      - 余韻を残すオチ
      - 皮肉や自虐で印象的に
      - 決意表明で力強く
      - テーマの核心を突く

    （以下、バース2と同様の手順）

    ---

    # 最終出力

    全{num_verse}バース完成後、最終的な歌詞のみを出力。
    - 小節ごとに改行
    - バース間は空行
    - 【】などの記号は外してシンプルに出力

    ## 出力例
    ```
    俺は東京生まれHIPHOP育ち
    悪そうな奴は大体友達
    悪そうな奴と大体同じ
    裏の道歩き見てきたこの街

    渋谷 六本木
    そう思春期もも早々に
    これにぞっこんに
    カバンなら置き放してきた高校に
    ```
    """

    return prompt


